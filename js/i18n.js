let lang = 'th';

export const getLang = () => lang;

/** ตั้งภาษา (ค่าที่ไม่รู้จักจะเป็นไทย) และเก็บลง storage ถ้ามี */
export function setLang(next, storage = globalThis.localStorage) {
  lang = LANGS.includes(next) ? next : 'th';
  try { storage?.setItem(LANG_KEY, lang); } catch { /* storage ใช้ไม่ได้ ก็ใช้แค่ในหน่วยความจำ */ }
  if (globalThis.document) document.documentElement.lang = lang;
  return lang;
}

/** อ่านภาษาที่เคยเลือกไว้ในเครื่อง */
export function initLang(storage = globalThis.localStorage) {
  let saved = null;
  try { saved = storage?.getItem(LANG_KEY); } catch { /* ignore */ }
  return setLang(saved ?? 'th', storage);
}

/** ข้อความตามภาษาปัจจุบัน แทน {ชื่อ} ด้วยค่าใน params */
export function t(key, params) {
  const s = DICT[lang][key] ?? DICT.th[key] ?? key;
  if (!params) return s;
  return s.replace(/\{([\w-]+)\}/g, (m, k) => (params[k] ?? m));
}

/** สำหรับเทสต์: คีย์ที่มีในภาษาหนึ่งแต่ไม่มีในอีกภาษา */
export function missingKeys() {
  const th = Object.keys(DICT.th);
  const en = Object.keys(DICT.en);
  return { en: th.filter((k) => !(k in DICT.en)), th: en.filter((k) => !(k in DICT.th)) };
}

/** สำหรับเทสต์: คีย์ทั้งหมด */
export const allKeys = () => Object.keys(DICT.th);
